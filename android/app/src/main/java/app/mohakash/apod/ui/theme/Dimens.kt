package app.mohakash.apod.ui.theme

import androidx.compose.ui.unit.dp

/**
 * The spacing, sizing and radius tokens of the app.
 *
 * Nothing in the UI hard-codes a size — everything comes from here.
 */
object MohakashDimens {

    /** The horizontal padding of every screen. */
    val SidePadding = 20.dp

    /** The height of the top bar. */
    val TopBarHeight = 56.dp

    /** The height of the bottom navigation bar. */
    val BottomNavHeight = 72.dp

    /** The minimum size of a touch target. */
    val TouchTarget = 48.dp

    /** Radius of picture placeholders and thumbnails. */
    val ImageRadius = 10.dp

    /** Radius of cards and saved tiles. */
    val CardRadius = 12.dp

    /** Radius of fully rounded pills. */
    val PillRadius = 24.dp

    /** Radius of the primary buttons. */
    val ButtonRadius = 26.dp

    /** Radius of the top corners of a sheet. */
    val SheetRadius = 24.dp

    /** Radius of a dialog. */
    val DialogRadius = 24.dp

    /** The height of the archive thumbnail. */
    val ArchiveThumbnailHeight = 56.dp

    /** The width of the archive thumbnail. */
    val ArchiveThumbnailWidth = 72.dp

    /** The height of the hero picture on the Today screen. */
    val TodayHeroHeight = 260.dp

    /** The height of the hero picture on the Today screen while offline. */
    val TodayOfflineHeroHeight = 240.dp

    /** The height of the hero picture on the detail screen. */
    val DetailHeroHeight = 280.dp

    /** The height of the poster on the video detail screen. */
    val VideoPosterHeight = 220.dp

    /** The width of the wallpaper preview inside the sheet. */
    val WallpaperPreviewWidth = 96.dp

    /** The radius of the wallpaper preview frame. */
    val WallpaperPreviewRadius = 14.dp

    /** The gap between two chips. */
    val ChipGap = 8.dp

    /** The visible height of a chip or a segment. */
    val ChipHeight = 40.dp

    /** The gap between two list rows. */
    val ListRowGap = 14.dp

    /** The radius of a banner. */
    val BannerRadius = 12.dp

    /** The radius of an archive thumbnail. */
    val ThumbnailRadius = 8.dp

    /** The radius of the top corners of the feed's bottom overlay. */
    val FeedOverlayRadius = 20.dp

    /** The size of the glass icon buttons in the feed's top chrome. */
    val FeedGlassButton = 44.dp
}
